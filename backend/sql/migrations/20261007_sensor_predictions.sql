-- Apply this additive migration in the Supabase SQL editor before deploying
-- the updated backend. Each row retains one forecast run for later comparison.
CREATE TABLE IF NOT EXISTS public.sensor_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id INTEGER NOT NULL REFERENCES public.rooms(room_id) ON DELETE CASCADE,
    base_time TIMESTAMPTZ NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    predictions JSONB NOT NULL CHECK (
        jsonb_typeof(predictions) = 'array' AND jsonb_array_length(predictions) > 0
    ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (room_id, base_time, generated_at)
);

CREATE INDEX IF NOT EXISTS sensor_predictions_latest_room_idx
    ON public.sensor_predictions (room_id, base_time DESC, generated_at DESC);

-- Clients retrieve forecasts through the backend's authenticated room stream.
ALTER TABLE public.sensor_predictions ENABLE ROW LEVEL SECURITY;
